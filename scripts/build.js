// Builds the browser bundle files from source.
//   data/data.js                   sample data as a JS global (works when index.html is opened from disk)
//   index.html                     GitHub Pages entry (loads src/engine.js + data/data.js)
//   dist/appointment-console.html  single self-contained file (engine + data inlined) to share or host anywhere
// Usage: node scripts/build.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), rd = p => fs.readFileSync(path.join(root, p), 'utf8');
const data = { interactions: rd('data/appointment_interactions.csv'), blind: rd('data/blind_set.csv'), challenge: rd('data/challenge_set.csv') };
const dataJs = `// Generated by scripts/build.js — synthetic data for the case study\nwindow.APPT_DATA = ${JSON.stringify(data)};\n`;
fs.writeFileSync(path.join(root, 'data/data.js'), dataJs);
const page = rd('app/page.html');
const wrap = body => `<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n${body.replace('<meta name="viewport" content="width=device-width, initial-scale=1">', '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">')}\n</html>\n`;
fs.writeFileSync(path.join(root, 'index.html'), wrap(page));
const inlined = page
  .replace('<script src="src/engine.js"></script>', () => `<script>\n${rd('src/engine.js')}\n</script>`)
  .replace('<script src="data/data.js"></script>', () => `<script>\n${dataJs}</script>`);
fs.writeFileSync(path.join(root, 'dist/appointment-console.html'), wrap(inlined));
fs.writeFileSync(path.join(root, 'dist/artifact.html'), inlined); // body-only variant for hosts that add their own skeleton
console.log('Built index.html, data/data.js, dist/appointment-console.html');
